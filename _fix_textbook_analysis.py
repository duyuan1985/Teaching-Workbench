def get_tc_text(tc):
    txt = ''
    for p in tc.findall(qn('w:p')):
        for r in p.findall(qn('w:r')):
            for elem in r:
                if elem.tag == qn('w:t'):
                    txt += elem.text or ''
    return txt.strip()

def set_check(tc):
    """设置勾"""
    for p in tc.findall(qn('w:p')):
        for r in p.findall(qn('w:r')):
            p.remove(r)
    p = tc.findall(qn('w:p'))
    if not p:
        p = [OxmlElement('w:p')]
        tc.append(p[0])
    p = p[0]
    r = OxmlElement('w:r')
    rPr = OxmlElement('w:rPr')
    rFonts = OxmlElement('w:rFonts')
    rFonts.set(qn('w:ascii'), '仿宋')
    rFonts.set(qn('w:eastAsia'), '仿宋')
    rFonts.set(qn('w:hAnsi'), '仿宋')
    rFonts.set(qn('w:cs'), '仿宋')
    rPr.append(rFonts)
    sz = OxmlElement('w:sz')
    sz.set(qn('w:val'), '21')
    rPr.append(sz)
    szCs = OxmlElement('w:szCs')
    szCs.set(qn('w:val'), '21')
    rPr.append(szCs)
    r.append(rPr)
    t = OxmlElement('w:t')
    t.text = '√'
    r.append(t)
    p.append(r)

def set_multiline_cell(tc, text, font_name='仿宋', font_size='21'):
    """设置多行文本"""
    paras = tc.findall(qn('w:p'))
    if not paras:
        p = OxmlElement('w:p')
        tc.append(p)
        paras = [p]
    p = paras[0]
    for r in p.findall(qn('w:r')):
        p.remove(r)
    lines = text.split('\n')
    r = OxmlElement('w:r')
    rPr = OxmlElement('w:rPr')
    rFonts = OxmlElement('w:rFonts')
    rFonts.set(qn('w:ascii'), font_name)
    rFonts.set(qn('w:eastAsia'), font_name)
    rFonts.set(qn('w:hAnsi'), font_name)
    rFonts.set(qn('w:cs'), font_name)
    rPr.append(rFonts)
    sz = OxmlElement('w:sz')
    sz.set(qn('w:val'), font_size)
    rPr.append(sz)
    szCs = OxmlElement('w:szCs')
    szCs.set(qn('w:val'), font_size)
    rPr.append(szCs)
    r.append(rPr)
    for li, line in enumerate(lines):
        if li > 0:
            br = OxmlElement('w:br')
            r.append(br)
        t_elem = OxmlElement('w:t')
        t_elem.set(qn('xml:space'), 'preserve')
        t_elem.text = line
        r.append(t_elem)
    p.append(r)
    for extra_p in paras[1:]:
        tc.remove(extra_p)

